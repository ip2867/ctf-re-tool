// ============ 标准分组密码常量表（单一事实来源）============
// 为什么单独成文件：
//   1) 扫描器 / 结构推理 / 解密器生成器都要用同一份标准表，散落三处必然漂移；
//   2) AI 通过 scan_crypto 看到的是"与哪个标准算法差多少"，依赖这里的权威数据；
//   3) 测试可以直接 require 本文件做一致性校验。
//
// 覆盖策略（诚实标注）：
//   · AES / SM4：**完整表**，可做精确匹配与仿射关系判定。
//   · DES / Blowfish：只给**结构元数据**（表形状、轮数、位宽），不做逐项表匹配——
//     这两者的表项数量大（DES 8×64、Blowfish 18+4×256），且变体题几乎都会整表替换，
//     用"形状"识别比用"精确表"更实用。误判风险由形状约束控制（见 detectTableShapes）。
//   · 其它（Camellia/ARIA/SEED）：仅登记名称与结构，暂不参与匹配。

// ---------- 生成 AES S 盒（GF(2^8) 求逆 + 仿射变换），避免手抄 256 项出错 ----------
function buildAesSbox() {
  const mul = (a, b) => {
    let p = 0;
    for (let i = 0; i < 8; i++) {
      if (b & 1) p ^= a;
      const hi = a & 0x80;
      a = (a << 1) & 0xff;
      if (hi) a ^= 0x1b;
      b >>= 1;
    }
    return p;
  };
  const inv = new Array(256).fill(0);
  for (let a = 1; a < 256; a++) for (let b = 1; b < 256; b++) if (mul(a, b) === 1) { inv[a] = b; break; }
  const rot = (x, n) => ((x << n) | (x >>> (8 - n))) & 0xff;
  const out = [];
  for (let i = 0; i < 256; i++) {
    const x = inv[i];
    out.push((x ^ rot(x, 1) ^ rot(x, 2) ^ rot(x, 3) ^ rot(x, 4) ^ 0x63) & 0xff);
  }
  return out;
}

const AES_SBOX = buildAesSbox();
const AES_INV_SBOX = (() => {
  const inv = new Array(256).fill(0);
  for (let i = 0; i < 256; i++) inv[AES_SBOX[i]] = i;
  return inv;
})();

